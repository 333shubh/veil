// E8: what does going sparse buy? Setup and per-round cost against N for Veil at E7's k and t, and for the same
// protocol on a complete graph (k = N - 1, t = floor((N - 1)/2) + 1).
// Run: npm run e8   (writes experiments/results/e8.md and e8.json)
import { choose, DESIGN } from '../src/params.ts';
import type { MeterId } from '../src/protocol.ts';
import { everyone, runRound, setupGroup } from '../src/simulation.ts';
import { environment, ms, timed, writeResult } from './lib.ts';
import { encapsulationBytes, keysBytes, perMeter } from './wire.ts';

const SIZES = [50, 100, 200];
const ROUNDS = 5;

interface Cost {
  k: number;
  t: number;
  setupMs: number; // whole group, all meters and the coordinator
  setupBytes: number; // per meter: its keys out, its neighbours' keys in, ML-KEM encapsulations both ways
  meterMs: number; // per meter per round
  coordinatorMs: number; // per round
  roundBytes: number; // per meter per round, sent plus received
}

function cost(n: number, k: number, t: number): Cost {
  const ids: MeterId[] = Array.from({ length: n }, (_, i) => i + 1);
  const [g, setupMs] = timed(() => setupGroup(ids, 1, k, t));
  let meterMs = 0;
  let coordinatorMs = 0;
  let roundBytes = 0;
  for (let r = 0; r < ROUNDS; r++) {
    const trace = runRound(g, r, new Map(ids.map((id) => [id, 1000n])), everyone(ids));
    if (trace.result.status !== 'published') throw new Error(`round ${r} ${trace.result.status}`);
    meterMs += (trace.ms.report + trace.ms.confirm + trace.ms.release) / n;
    coordinatorMs += trace.ms.close + trace.ms.collect + trace.ms.recover;
    for (const b of perMeter(trace).values()) {
      roundBytes += (b.sent.report + b.sent.confirm + b.sent.release + b.received.active + b.received.confirms + b.received.final) / n;
    }
  }
  return { k, t, setupMs, setupBytes: keysBytes * (k + 1) + k * encapsulationBytes, meterMs: meterMs / ROUNDS, coordinatorMs: coordinatorMs / ROUNDS, roundBytes: roundBytes / ROUNDS };
}

const started = performance.now();
const rows = SIZES.map((n) => {
  const { k, t } = choose(n, DESIGN)!;
  const sparse = cost(n, k, t);
  const complete = cost(n, n - 1, Math.floor((n - 1) / 2) + 1);
  const ratio = (f: (c: Cost) => number) => f(sparse) / f(complete);
  const row = {
    n,
    sparse,
    complete,
    ratio: { setup: ratio((c) => c.setupMs), meter: ratio((c) => c.meterMs), coordinator: ratio((c) => c.coordinatorMs), bytes: ratio((c) => c.roundBytes) },
  };
  console.log(`[e8] N=${n}: sparse/complete setup ${(row.ratio.setup * 100).toFixed(0)}%, meter ${(row.ratio.meter * 100).toFixed(0)}%, coordinator ${(row.ratio.coordinator * 100).toFixed(0)}%, bytes ${(row.ratio.bytes * 100).toFixed(0)}%`);
  return row;
});

const seconds = ((performance.now() - started) / 1000).toFixed(1);
const pct = (x: number) => `${(x * 100).toFixed(0)}%`;
const md = [
  '# E8: what does going sparse buy?',
  '',
  `Generated by \`npm run e8\` on ${new Date().toISOString().slice(0, 10)}: ${environment()}. Run time ${seconds} s.`,
  '',
  `Same protocol, same machine; the complete graph uses k = N - 1 and t = floor((N - 1)/2) + 1. Setup time covers the ` +
    `whole group (keys, signatures, key exchange); round figures average ${ROUNDS} rounds with no dropouts. Bytes per ` +
    'meter per round include the active and final set announcements, which are the same for both.',
  '',
  '| N | graph | k | t | setup (ms, group) | setup bytes per meter | per meter per round (ms) | coordinator per round (ms) | bytes per meter per round |',
  '|---|---|---|---|---|---|---|---|---|',
  ...rows.flatMap((r) =>
    (['sparse', 'complete'] as const).map((kind) => {
      const c = r[kind];
      return `| ${r.n} | ${kind} | ${c.k} | ${c.t} | ${ms(c.setupMs)} | ${c.setupBytes} | ${ms(c.meterMs)} | ${ms(c.coordinatorMs)} | ${Math.round(c.roundBytes)} |`;
    }),
  ),
  '',
  '| N | sparse / complete: setup | meter time | coordinator time | bytes |',
  '|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.n} | ${pct(r.ratio.setup)} | ${pct(r.ratio.meter)} | ${pct(r.ratio.coordinator)} | ${pct(r.ratio.bytes)} |`),
];
writeResult('e8', md, { environment: environment(), seconds: Number(seconds), rows });
console.log(`[e8] done in ${seconds} s`);
