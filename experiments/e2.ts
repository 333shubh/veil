// E2: how many bytes per round? Per-meter bytes on the wire against k, with and without dropouts, plus setup.
// Run: npm run e2   (writes experiments/results/e2.md and e2.json)
import { hkdf, u32Stream } from '../src/crypto.ts';
import type { MeterId } from '../src/protocol.ts';
import { everyone, runRound, setupGroup, type Pattern } from '../src/simulation.ts';
import { environment, writeResult } from './lib.ts';
import { BYTES, encapsulationBytes, keysBytes, perMeter, reportBytes, setBytes, setListBytes, type MeterBytes } from './wire.ts';

const N = 200;
const KS = [8, 16, 32, 54, 80];
const ROUNDS = 10;
const DROPOUT = 0.1; // before the deadline; then 2% more before confirming, 2% before checking and 2% before releasing
const LATE = 0.02;
const SCALE_N = [100, 200, 1_000, 10_000];

const next = u32Stream(hkdf(Buffer.from('veil E2 seed 1'), Buffer.from('e2')));
const chance = (p: number) => next() / 2 ** 32 < p;

function pattern(ids: MeterId[], dropouts: boolean): Pattern {
  if (!dropouts) return everyone(ids);
  const reporting = ids.filter(() => !chance(DROPOUT));
  const confirming = reporting.filter(() => !chance(LATE));
  const checking = confirming.filter(() => !chance(LATE));
  const releasing = checking.filter(() => !chance(LATE));
  return { reporting: new Set(reporting), confirming: new Set(confirming), checking: new Set(checking), releasing: new Set(releasing) };
}

const sum = (b: MeterBytes) => ({
  sent: b.sent.report + b.sent.confirm + b.sent.check + b.sent.release + b.sent.unmask,
  received: b.received.sets + b.received.confirms + b.received.checks,
});

const started = performance.now();
const rows: Record<string, number | string>[] = [];
const ids: MeterId[] = Array.from({ length: N }, (_, i) => i + 1);
let round = 0;
for (const k of KS) {
  const g = setupGroup(ids, 1, k, Math.floor(k / 2) + 1);
  for (const dropouts of [false, true]) {
    const all: MeterBytes[] = [];
    let published = 0;
    for (let r = 0; r < ROUNDS; r++) {
      const readings = new Map(ids.map((id) => [id, 1000n]));
      const trace = runRound(g, round++, readings, pattern(ids, dropouts));
      if (trace.result.status === 'published') published++;
      all.push(...perMeter(trace, N).values());
    }
    const mean = (f: (b: MeterBytes) => number) => Math.round(all.reduce((a, b) => a + f(b), 0) / all.length);
    const max = (f: (b: MeterBytes) => number) => Math.max(...all.map(f));
    const row = {
      k,
      dropouts: dropouts ? `${DROPOUT * 100}% + ${LATE * 100}% + ${LATE * 100}% + ${LATE * 100}%` : 'none',
      published,
      report: mean((b) => b.sent.report),
      confirm: mean((b) => b.sent.confirm),
      check: mean((b) => b.sent.check),
      release: mean((b) => b.sent.release),
      unmask: mean((b) => b.sent.unmask),
      sent: mean((b) => sum(b).sent),
      sentMax: max((b) => sum(b).sent),
      confirmsIn: mean((b) => b.received.confirms),
      checksIn: mean((b) => b.received.checks),
      announcements: mean((b) => b.received.sets),
      received: mean((b) => sum(b).received),
      receivedMax: max((b) => sum(b).received),
    };
    rows.push(row);
    console.log(`[e2] k=${k} ${row.dropouts}: sent ${row.sent} B, received ${row.received} B (sets ${row.announcements} B), ${published}/${ROUNDS} published`);
  }
}

const seconds = ((performance.now() - started) / 1000).toFixed(1);
// On average a meter encapsulates to half its neighbours and receives encapsulations from the other half.
const setup = KS.map((k) => ({
  k,
  sent: keysBytes + (k / 2) * encapsulationBytes,
  received: k * keysBytes + (k / 2) * encapsulationBytes + N * (BYTES.id + BYTES.key) + (4 + 4 + BYTES.hash + BYTES.signature),
}));
const md = [
  '# E2: how many bytes per round?',
  '',
  `Generated by \`npm run e2\` on ${new Date().toISOString().slice(0, 10)}: ${environment()}. Run time ${seconds} s.`,
  '',
  `Group of ${N} meters, ${ROUNDS} rounds per row, t = floor(k/2) + 1 (t barely changes sizes). Messages are counted in a ` +
    `fixed-width encoding: ids and rounds 4 bytes, ring values 8, hashes and round secrets 32, Ed25519 signatures 64, ` +
    `MAC tags 16, Shamir shares 33 (49 once sealed). Announced sets (U, F, and an unmask request when a meter in F goes ` +
    `silent) are bitmaps over the anchored roster, ${setBytes(N)} bytes each at N = ${N}. Means per meter per round, over ` +
    'the meters that reported.',
  '',
  '## Per round',
  '',
  '| k | dropouts | published | report | confirmation | check | release | unmask | sent | sent (max) | confirmations in | checks in | sets in | received | received (max) |',
  '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|',
  ...rows.map(
    (r) =>
      `| ${r.k} | ${r.dropouts} | ${r.published}/${ROUNDS} | ${r.report} | ${r.confirm} | ${r.check} | ${r.release} | ${r.unmask} | ${r.sent} | ${r.sentMax} | ${r.confirmsIn} | ${r.checksIn} | ${r.announcements} | ${r.received} | ${r.receivedMax} |`,
  ),
  '',
  `A report alone is ${reportBytes} bytes (id, round, 64-bit masked value, 16-byte tag). Paillier's report carries a ` +
    `256-byte (1024-bit key) or 512-byte (2048-bit key) ciphertext instead of the 8-byte value (E1). With no dropouts a ` +
    'release is the round secret alone; the self-mask shares a meter received at confirmation are passed on only when a ' +
    'meter in F goes silent (the unmask column).',
  '',
  '## What grows with N',
  '',
  'Everything a meter sends grows with k. What it receives also grows with k, except the announced sets. Phase 7 sent ' +
    'U and F as id lists; they are now bitmaps over the roster, 32 times smaller.',
  '',
  '| N | U and F as id lists, all reporting (bytes per meter per round) | as roster bitmaps |',
  '|---|---|---|',
  ...SCALE_N.map((n) => `| ${n} | ${2 * setListBytes(n)} | ${2 * setBytes(n)} |`),
  '',
  '## Setup, once per epoch',
  '',
  `Each meter sends its signed epoch keys (${keysBytes} bytes, including a 1,184-byte ML-KEM key) and an ML-KEM ` +
    `encapsulation (${encapsulationBytes} bytes) to each neighbour with a higher id, and receives its k neighbours' keys, ` +
    'their encapsulations, the roster (id and device key per member, needed to recompute the graph) and the anchor. ' +
    'Averages over a meter\'s neighbours, half of which have a higher id.',
  '',
  '| k | sent | received (N = 200) |',
  '|---|---|---|',
  ...setup.map((s) => `| ${s.k} | ${s.sent} | ${s.received} |`),
];
writeResult('e2', md, { environment: environment(), seconds: Number(seconds), n: N, rows, setup, reportBytes, setBytes: setBytes(N) });
console.log(`[e2] done in ${seconds} s`);
