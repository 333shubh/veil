// Indian dropout: how many of an epoch's meters miss a round, measured on CEEW's smart-meter data from Mathura and
// Bareilly, Uttar Pradesh (2020, one reading every 3 minutes, CC0: doi:10.7910/DVN/GOCHJH). Sets DESIGN.dropout.
// Data: download the 2020 CSVs for both districts into $VEIL_DATA/ceew/ (default ~/veil-data/ceew/) as
// mathura_2020.csv and bareilly_2020.csv.
// Run: npm run india-dropout   (writes experiments/results/india-dropout.md and .json)
import { createReadStream } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { createInterface } from 'node:readline';
import { DESIGN } from '../src/params.ts';
import { environment, writeResult } from './lib.ts';

const DATA = join(process.env.VEIL_DATA ?? join(homedir(), 'veil-data'), 'ceew');
const DISTRICTS = ['mathura_2020', 'bareilly_2020'];
const SLOT = 180; // seconds per reading
const EPOCHS = [
  ['daily', 480],
  ['hourly', 20],
] as const;
const SHORT_GAP = 5; // slots: gaps up to 15 minutes count as transient loss
const MIN_DAYS = 30;

/** Slots in which each meter reported with the supply on (voltage at least 50 V). */
async function powered(district: string): Promise<Map<string, Set<number>>> {
  const on = new Map<string, Set<number>>();
  const lines = createInterface({ input: createReadStream(join(DATA, `${district}.csv`)) });
  let header = true;
  for await (const line of lines) {
    if (header) {
      header = false;
      continue;
    }
    const [stamp, , volt, , , meter] = line.split(',');
    const v = Number(volt);
    const t = Date.parse(`${stamp!.slice(0, 19).replace(' ', 'T')}Z`);
    if (!meter || Number.isNaN(t) || !(v >= 50)) continue;
    let s = on.get(meter);
    if (!s) on.set(meter, (s = new Set()));
    s.add(Math.floor(t / 1000 / SLOT));
  }
  for (const [m, s] of on) {
    const [lo, hi] = range(s);
    if (hi - lo < (MIN_DAYS * 86_400) / SLOT) on.delete(m);
  }
  return on;
}

function range(values: Iterable<number>): [number, number] {
  let lo = Infinity;
  let hi = -Infinity;
  for (const v of values) {
    if (v < lo) lo = v;
    if (v > hi) hi = v;
  }
  return [lo, hi];
}

const quantile = (xs: number[], p: number) => [...xs].sort((a, b) => a - b)[Math.min(xs.length - 1, Math.floor(p * xs.length))]!;
const mean = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / xs.length;
const pct = (x: number) => `${(x * 100).toFixed(1)}%`;

const started = performance.now();
const results = [];
for (const district of DISTRICTS) {
  const on = await powered(district);
  const spans = [...on.values()].map(range);
  const [lo, hi] = [Math.min(...spans.map((r) => r[0])), Math.max(...spans.map((r) => r[1]))];

  // Transient loss: gaps of up to 15 minutes, as a share of each meter's span.
  const transient = [...on.values()].map((s) => {
    const slots = [...s].sort((a, b) => a - b);
    let short = 0;
    for (let i = 1; i < slots.length; i++) {
      const gap = slots[i]! - slots[i - 1]! - 1;
      if (gap > 0 && gap <= SHORT_GAP) short += gap;
    }
    return short / (slots.at(-1)! - slots[0]! + 1);
  });

  // Dropout within an epoch: the roster is the meters reporting at its first slot; in each later slot where a round
  // could run (at least 3 roster meters report), count the share of the roster that is missing.
  const epochs = EPOCHS.map(([label, length]) => {
    const missing: number[] = [];
    let count = 0;
    for (let start = lo; start < hi; start += length) {
      const roster = [...on.values()].filter((s) => s.has(start));
      if (roster.length < 10) continue;
      count++;
      for (let slot = start + 1; slot < start + length; slot++) {
        const up = roster.filter((s) => s.has(slot)).length;
        if (up >= 3) missing.push(1 - up / roster.length);
      }
    }
    return { label, epochs: count, rounds: missing.length, mean: mean(missing), median: quantile(missing, 0.5), p90: quantile(missing, 0.9), p99: quantile(missing, 0.99) };
  });
  const row = { district, meters: on.size, transient: { mean: mean(transient), p90: quantile(transient, 0.9) }, epochs };
  results.push(row);
  console.log(`[india-dropout] ${district}: ${on.size} meters; daily-epoch dropout mean ${pct(epochs[0]!.mean)}, p99 ${pct(epochs[0]!.p99)}`);
}

const daily = results.map((r) => r.epochs[0]!.mean);
const seconds = ((performance.now() - started) / 1000).toFixed(1);
const md = [
  '# Dropout in Indian smart-meter data',
  '',
  `Generated by \`npm run india-dropout\` on ${new Date().toISOString().slice(0, 10)}: ${environment()}. Run time ${seconds} s.`,
  '',
  'Data: CEEW, "High frequency smart meter data from two districts in India (Mathura and Bareilly)", Harvard Dataverse, ' +
    'doi:10.7910/DVN/GOCHJH, CC0; 2020 files, one reading every 3 minutes. A reading counts only if the supply was on ' +
    `(voltage at least 50 V); meters with under ${MIN_DAYS} days of data are left out.`,
  '',
  "Dropout within an epoch is what E7's dropout rate means: the epoch's roster is the meters reporting at its first " +
    'slot, and each later slot where at least 3 of them report counts the share of the roster that is missing. Power ' +
    'cuts make this bursty, so the tail matters as much as the mean.',
  '',
  '| district | meters | transient loss (gaps up to 15 min), mean | epoch | rounds | missing per round: mean | median | p90 | p99 |',
  '|---|---|---|---|---|---|---|---|---|',
  ...results.flatMap((r) =>
    r.epochs.map((e) => `| ${r.district} | ${r.meters} | ${pct(r.transient.mean)} | ${e.label} | ${e.rounds} | ${pct(e.mean)} | ${pct(e.median)} | ${pct(e.p90)} | ${pct(e.p99)} |`),
  ),
  '',
  `Design point: dropout ${DESIGN.dropout * 100}% (\`src/params.ts\`), against a measured daily-epoch mean of ` +
    `${daily.map(pct).join(' and ')}. The p90 and p99 rounds lose far more because power cuts take many meters at once; ` +
    'E4 measures those levels directly (every published total stays exact; fewer reporters are included).',
];
writeResult('india-dropout', md, { environment: environment(), seconds: Number(seconds), data: 'doi:10.7910/DVN/GOCHJH', results });
console.log(`[india-dropout] done in ${seconds} s`);
