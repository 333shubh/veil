// E1: how much does a meter pay per report? Veil's masking (and its whole round) against Paillier encryption.
// Run: npm run e1   (writes experiments/results/e1.md and e1.json)
import { isAborted, type MeterId } from '../src/protocol.ts';
import { setupGroup } from '../src/simulation.ts';
import { environment, ms, stats, timed, writeResult, type Stats } from './lib.ts';
import { Paillier } from './paillier.ts';
import { reportBytes } from './wire.ts';

const RUNS = 10_000;
const ROUNDS = 500;
// (k, t): the last three are E7's choices for groups of 100, 1,000 and 10,000 meters.
const NEIGHBOURHOODS: [number, number][] = [[8, 5], [16, 9], [38, 21], [68, 43], [80, 51]];
const PAILLIER_BITS = [1024, 2048];

interface Row {
  scheme: string;
  k?: number;
  bits?: number;
  runs: number;
  stats: Stats;
  bytes?: number;
}

const rows: Row[] = [];
const started = performance.now();

// Set up one group per k: a complete group of k + 1 meters gives every meter exactly k neighbours, as in a sparse group.
const groups = NEIGHBOURHOODS.map(([k, t]) => {
  const ids: MeterId[] = Array.from({ length: k + 1 }, (_, i) => i + 1);
  return { k, ids, g: setupGroup(ids, 1, k, t) };
});
const paillier = PAILLIER_BITS.map((bits) => new Paillier(bits));

// Per-report cost, interleaved run by run so every scheme sees the same machine state.
const masking = groups.map(() => [] as number[]);
const encryption = paillier.map(() => [] as number[]);
for (let r = 0; r < RUNS; r++) {
  groups.forEach(({ g }, i) => masking[i]!.push(timed(() => g.meters.get(1)!.report(r, 1234n))[1]));
  paillier.forEach((p, i) => encryption[i]!.push(timed(() => p.encrypt(1234n))[1]));
}
groups.forEach(({ k }, i) => rows.push({ scheme: 'Veil masking (report)', k, runs: RUNS, stats: stats(masking[i]!), bytes: reportBytes }));
paillier.forEach((p, i) => rows.push({ scheme: 'Paillier encryption', bits: p.bits, runs: RUNS, stats: stats(encryption[i]!), bytes: 4 + 4 + p.ciphertextBytes + 16 }));
for (const r of rows) console.log(`[e1] ${r.scheme} ${r.k ?? r.bits}: median ${ms(r.stats.median)} ms`);

// The whole round for one meter: every meter plays its part, only meter 1 is timed.
for (const { k, ids, g } of groups) {
  const round: number[] = [];
  for (let r = RUNS; r < RUNS + ROUNDS; r++) {
    let spent = 0;
    const reports = ids.map((id) => {
      const [rep, dt] = timed(() => g.meters.get(id)!.report(r, 1234n));
      if (id === 1) spent += dt;
      return rep;
    });
    const closed = g.coordinator.close(r, reports);
    if (closed.status !== 'open') throw new Error('round suppressed');
    const confirms = ids.map((id) => {
      const [c, dt] = timed(() => g.meters.get(id)!.confirm(r, closed.active));
      if (id === 1) spent += dt;
      if (isAborted(c)) throw new Error(c.aborted);
      return c;
    });
    const collected = g.coordinator.collect(confirms);
    if (collected.status !== 'open') throw new Error('round suppressed');
    const releases = ids.map((id) => {
      const [rel, dt] = timed(() => g.meters.get(id)!.release(r, collected.final, collected.inbox.get(id) ?? []));
      if (id === 1) spent += dt;
      if (isAborted(rel)) throw new Error(rel.aborted);
      return rel;
    });
    if (g.coordinator.recover(releases).status !== 'published') throw new Error('round not published');
    round.push(spent);
  }
  rows.push({ scheme: 'Veil whole round (report, confirm, release)', k, runs: ROUNDS, stats: stats(round) });
  console.log(`[e1] k=${k}: whole round median ${ms(stats(round).median)} ms`);
}

const seconds = ((performance.now() - started) / 1000).toFixed(1);
const md = [
  '# E1: how much does a meter pay per report?',
  '',
  `Generated by \`npm run e1\` on ${new Date().toISOString().slice(0, 10)}: ${environment()}. Run time ${seconds} s.`,
  '',
  'Veil masking is `Meter.report` (self-mask, k pair masks, report MAC). The whole round adds the meter\'s confirmation ' +
    '(correction, t-of-n shares of the round\'s self-mask, neighbour MACs, one Ed25519 co-signature) and its release. ' +
    'Paillier encryption is c = (1 + m n) r^n mod n^2 with OpenSSL modular exponentiation. Masking and encryption are ' +
    'timed in turn within each run, in one process on one core.',
  '',
  'Only a laptop was available; the Raspberry Pi and Cortex-M runs the plan asks for are still to do.',
  '',
  '| scheme | k or key size | runs | median (ms) | p95 (ms) | max (ms) | bytes per report |',
  '|---|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.scheme} | ${r.k !== undefined ? `k = ${r.k}` : `${r.bits} bits`} | ${r.runs} | ${ms(r.stats.median)} | ${ms(r.stats.p95)} | ${ms(r.stats.max)} | ${r.bytes ?? ''} |`),
];
writeResult('e1', md, { environment: environment(), seconds: Number(seconds), rows });
console.log(`[e1] done in ${seconds} s`);
