// E3: how does the operator's work scale? Coordinator time per round against N for Veil (E7's k and t), the same
// protocol on a complete graph, and Paillier aggregation plus decryption.
// Run: npm run e3   (writes experiments/results/e3.md and e3.json)
import { hkdf, u32Stream } from '../src/crypto.ts';
import { choose, DESIGN } from '../src/params.ts';
import type { MeterId } from '../src/protocol.ts';
import { coordinatorMs, meterMs as meterTime, runRound, setupGroup, type Pattern } from '../src/simulation.ts';
import { environment, ms, stats, timed, writeResult, type Stats } from './lib.ts';
import { Paillier } from './paillier.ts';

const VEIL_N = [100, 200, 500, 1000, 2000];
const COMPLETE_N = [50, 100, 200];
const PAILLIER_N: Record<number, number[]> = { 1024: [100, 1000, 10000], 2048: [100, 1000, 2000] };
const ROUNDS = 10;

const next = u32Stream(hkdf(Buffer.from('veil E3 seed 1'), Buffer.from('e3')));
const chance = (p: number) => next() / 2 ** 32 < p;

const SILENT = 0.01; // in the fallback rows: meters that go silent after checking, so their self-masks are rebuilt

/** DESIGN.dropout of the meters miss each round; with `silent`, SILENT of the rest go quiet after checking. */
function dropouts(ids: MeterId[], silent: boolean): Pattern {
  const reporting = new Set(ids.filter(() => !chance(DESIGN.dropout)));
  const releasing = silent ? new Set([...reporting].filter(() => !chance(SILENT))) : reporting;
  return { reporting, confirming: reporting, releasing };
}

interface Row {
  scheme: string;
  n: number;
  k?: number;
  t?: number;
  rounds: number;
  coordinator: Stats; // ms per round
  meter?: number; // mean ms per meter per round, for context
}

/** One group, two schemes: the common round, then rounds where some meters go silent after checking. */
function veil(schemes: [string, string?], n: number, k: number, t: number): Row[] {
  const ids: MeterId[] = Array.from({ length: n }, (_, i) => i + 1);
  const [g, setupMs] = timed(() => setupGroup(ids, 1, k, t));
  let r = 0;
  const run = (scheme: string, silent: boolean): Row => {
    const coordinator: number[] = [];
    let meterMs = 0;
    let meterRounds = 0;
    for (let i = 0; i < ROUNDS; i++, r++) {
      const pattern = dropouts(ids, silent);
      const trace = runRound(g, r, new Map(ids.map((id) => [id, 1000n])), pattern);
      if (trace.result.status !== 'published') throw new Error(`round ${r} ${trace.result.status}`);
      coordinator.push(coordinatorMs(trace));
      meterMs += meterTime(trace);
      meterRounds += pattern.reporting.size;
    }
    const row = { scheme, n, k, t, rounds: ROUNDS, coordinator: stats(coordinator), meter: meterMs / meterRounds };
    console.log(`[e3] ${scheme} N=${n} k=${k}: coordinator median ${ms(row.coordinator.median)} ms (setup ${(setupMs / 1000).toFixed(1)} s)`);
    return row;
  };
  return [run(schemes[0], false), ...(schemes[1] ? [run(schemes[1], true)] : [])];
}

const started = performance.now();
const rows: Row[] = [];
for (const n of VEIL_N) {
  const { k, t } = choose(n, DESIGN)!;
  rows.push(...veil(['Veil (E7 k)', `Veil (E7 k), ${SILENT * 100}% silent after checking`], n, k, t));
}
for (const n of COMPLETE_N) rows.push(...veil(['Veil on a complete graph'], n, n - 1, Math.floor((n - 1) / 2) + 1));

for (const [bits, sizes] of Object.entries(PAILLIER_N)) {
  const p = new Paillier(Number(bits));
  const ciphertexts = Array.from({ length: Math.max(...sizes) }, () => p.encrypt(1000n));
  for (const n of sizes) {
    const samples = Array.from({ length: ROUNDS }, () =>
      timed(() => {
        let acc = ciphertexts[0]!;
        for (let i = 1; i < n; i++) acc = p.add(acc, ciphertexts[i]!);
        if (p.decrypt(acc) !== 1000n * BigInt(n)) throw new Error('Paillier sum mismatch');
      })[1],
    );
    rows.push({ scheme: `Paillier-${bits}`, n, rounds: ROUNDS, coordinator: stats(samples) });
    console.log(`[e3] Paillier-${bits} N=${n}: median ${ms(stats(samples).median)} ms`);
  }
}

/** Least-squares slope of log(time) against log(N): about 1 means linear. */
function exponent(scheme: string): number {
  const pts = rows.filter((r) => r.scheme === scheme).map((r) => [Math.log(r.n), Math.log(r.coordinator.median)] as const);
  const mx = pts.reduce((a, [x]) => a + x, 0) / pts.length;
  const my = pts.reduce((a, [, y]) => a + y, 0) / pts.length;
  return pts.reduce((a, [x, y]) => a + (x - mx) * (y - my), 0) / pts.reduce((a, [x]) => a + (x - mx) ** 2, 0);
}

const schemes = [...new Set(rows.map((r) => r.scheme))];
const growth = Object.fromEntries(schemes.map((s) => [s, Number(exponent(s).toFixed(2))]));
const seconds = ((performance.now() - started) / 1000).toFixed(1);
const md = [
  '# E3: how does the operator\'s work scale?',
  '',
  `Generated by \`npm run e3\` on ${new Date().toISOString().slice(0, 10)}: ${environment()}. Run time ${seconds} s.`,
  '',
  `Coordinator time per round: closing the round (report MACs), collecting confirmations (co-signatures), routing ` +
    `checks, gathering releases (revealed self-masks against their commitments, signed removals) and recovering the ` +
    `total. ${DESIGN.dropout * 100}% of meters miss each round. In the "silent after checking" rows, ${SILENT * 100}% of ` +
    'the reporters also go quiet after the check, so the coordinator asks for shares and rebuilds their self-masks. ' +
    `The complete-graph rows run the same protocol with k = N - 1 and t = floor((N - 1)/2) + 1. Paillier rows multiply N ` +
    `ciphertexts and decrypt the product. ${ROUNDS} rounds per row; the meters' own time is shown for context.`,
  '',
  '| scheme | N | k | t | coordinator median (ms) | p95 (ms) | per meter, mean (ms) |',
  '|---|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.scheme} | ${r.n} | ${r.k ?? ''} | ${r.t ?? ''} | ${ms(r.coordinator.median)} | ${ms(r.coordinator.p95)} | ${r.meter === undefined ? '' : ms(r.meter)} |`),
  '',
  'Growth exponent (slope of log time against log N; 1 is linear):',
  '',
  ...schemes.map((s) => `- ${s}: ${growth[s]}`),
];
writeResult('e3', md, { environment: environment(), seconds: Number(seconds), rows, growth });
console.log(`[e3] growth ${JSON.stringify(growth)}; done in ${seconds} s`);
