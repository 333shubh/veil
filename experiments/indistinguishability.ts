// Indistinguishability test: two reading vectors with the same total, run through the protocol many times. A classifier
// trained on everything the coordinator sees must do no better than chance; the same classifier on the raw readings
// is the control.
// Run: npm run indistinguishability   (writes experiments/results/indistinguishability.md and .json)
import { hkdf, u32Stream } from '../src/crypto.ts';
import { choose, DESIGN } from '../src/params.ts';
import type { MeterId } from '../src/protocol.ts';
import { sub } from '../src/ring.ts';
import { runRound, setupGroup } from '../src/simulation.ts';
import { environment, writeResult } from './lib.ts';

const N = 50;
const ROUNDS = 1000;
const SHIFT = 3000n; // W moved from meter 2 to meter 1 in vector B; the total is unchanged
const DROPOUT = 0.1; // among meters 3..N, so both vectors keep the same total
const SEED = 'veil indistinguishability seed 1';

const next = u32Stream(hkdf(Buffer.from(SEED), Buffer.from('indistinguishability')));
const uniform = () => next() / 2 ** 32;
const ids: MeterId[] = Array.from({ length: N }, (_, i) => i + 1);
const base = new Map(ids.map((id) => [id, BigInt(Math.floor(uniform() * 4000))]));
const vectorB = new Map(base);
vectorB.set(1, base.get(1)! + SHIFT);
vectorB.set(2, base.get(2)! - SHIFT);

const { k, t } = choose(N, DESIGN)!;
const group = setupGroup(ids, 1, k, t);
const toUnit = (v: bigint) => Number(v) / 2 ** 64;

/** What the coordinator can compute per meter: its report with the self-mask, correction and removal taken off. */
const masked: number[][] = [];
const raw: number[][] = [];
const labels: number[] = [];
const started = performance.now();
for (let r = 0; r < ROUNDS; r++) {
  const label = uniform() < 0.5 ? 0 : 1;
  const readings = label === 0 ? base : vectorB;
  const reporting = new Set(ids.filter((id) => id <= 2 || uniform() >= DROPOUT));
  const trace = runRound(group, r, readings, { reporting, confirming: reporting, releasing: reporting });
  if (trace.result.status !== 'published') throw new Error(`round ${r} ${trace.result.status}`);
  const ev = trace.result.evidence;
  const removals = new Map(ev.removals.map((e) => [e.id, e.value]));
  const contribution = new Map(ev.contributions.map((c) => [c.id, c]));
  masked.push(
    ids.map((id) => {
      const c = contribution.get(id);
      if (!c) return 0.5;
      const self = Buffer.from(ev.secrets.get(id)!).readBigUInt64LE(0);
      return toUnit(sub(sub(sub(c.y, self), c.correction), removals.get(id) ?? 0n));
    }),
  );
  raw.push(ids.map((id) => (reporting.has(id) ? Number(readings.get(id)!) / 10_000 : 0)));
  labels.push(label);
}

/** Logistic regression by batch gradient descent on standardised features; returns test accuracy. */
function accuracy(features: number[][]): { accuracy: number; ci: number; test: number } {
  const split = Math.floor(features.length * 0.7);
  const d = features[0]!.length;
  const mean = Array.from({ length: d }, (_, j) => features.slice(0, split).reduce((a, x) => a + x[j]!, 0) / split);
  const sd = Array.from({ length: d }, (_, j) => Math.sqrt(features.slice(0, split).reduce((a, x) => a + (x[j]! - mean[j]!) ** 2, 0) / split) || 1);
  const z = features.map((x) => x.map((v, j) => (v - mean[j]!) / sd[j]!));
  const w = new Array<number>(d + 1).fill(0);
  const predict = (x: number[]) => 1 / (1 + Math.exp(-(w[d]! + x.reduce((a, v, j) => a + v * w[j]!, 0))));
  for (let epoch = 0; epoch < 300; epoch++) {
    const grad = new Array<number>(d + 1).fill(0);
    for (let i = 0; i < split; i++) {
      const err = predict(z[i]!) - labels[i]!;
      z[i]!.forEach((v, j) => (grad[j]! += err * v));
      grad[d]! += err;
    }
    for (let j = 0; j <= d; j++) w[j]! -= 0.5 * (grad[j]! / split + (j < d ? 1e-3 * w[j]! : 0));
  }
  const test = features.length - split;
  let correct = 0;
  for (let i = split; i < features.length; i++) if ((predict(z[i]!) >= 0.5 ? 1 : 0) === labels[i]) correct++;
  const acc = correct / test;
  return { accuracy: acc, ci: 1.96 * Math.sqrt((acc * (1 - acc)) / test) || 1.96 * Math.sqrt(0.25 / test), test };
}

const view = accuracy(masked);
const control = accuracy(raw);
const seconds = ((performance.now() - started) / 1000).toFixed(1);
console.log(`[indistinguishability] coordinator's view: ${(view.accuracy * 100).toFixed(1)}% ± ${(view.ci * 100).toFixed(1)}; raw readings: ${(control.accuracy * 100).toFixed(1)}%`);

const md = [
  '# Indistinguishability test',
  '',
  `Generated by \`npm run indistinguishability\` on ${new Date().toISOString().slice(0, 10)}: ${environment()}. Seed "${SEED}". Run time ${seconds} s.`,
  '',
  `${N} meters, k = ${k}, t = ${t}. Vector B moves ${SHIFT} W from meter 2 to meter 1 of a fixed vector A, so both have ` +
    `the same total. ${ROUNDS} rounds, each A or B at random, with ${DROPOUT * 100}% of meters 3-${N} missing each round. ` +
    'For every meter the coordinator removes everything it can (the revealed or rebuilt self-mask, the correction and any removal) ' +
    'and the classifier sees what is left, one feature per meter. Logistic regression, trained on the first 70% of rounds ' +
    'and tested on the rest; the control trains the same classifier on the raw readings.',
  '',
  '| features | test rounds | accuracy (95% CI) |',
  '|---|---|---|',
  `| coordinator's view | ${view.test} | ${(view.accuracy * 100).toFixed(1)}% ± ${(view.ci * 100).toFixed(1)} |`,
  `| raw readings (control) | ${control.test} | ${(control.accuracy * 100).toFixed(1)}% ± ${(control.ci * 100).toFixed(1)} |`,
  '',
  Math.abs(view.accuracy - 0.5) <= view.ci
    ? 'The coordinator\'s view is at chance: 50% lies inside the interval.'
    : 'The coordinator\'s view is NOT at chance: 50% lies outside the interval.',
];
writeResult('indistinguishability', md, { environment: environment(), seconds: Number(seconds), seed: SEED, view, control });
console.log(`[indistinguishability] done in ${seconds} s`);
