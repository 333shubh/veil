// E6: does privacy cost forecasting accuracy? Next-day peak forecast from exact totals, from Veil's totals and from
// differentially private noisy totals. Veil's totals equal the exact ones, so its forecast is identical by construction:
// an invariant, checked here bit for bit, not a finding.
// Run: npm run e6   (writes experiments/results/e6.md and e6.json)
import { hkdf, u32Stream } from '../src/crypto.ts';
import { simulateLoad } from '../src/load.ts';
import { choose, DESIGN } from '../src/params.ts';
import type { MeterId } from '../src/protocol.ts';
import { everyone, runRound, setupGroup } from '../src/simulation.ts';
import { environment, writeResult } from './lib.ts';

const HOMES = 100;
const DAYS = 60;
const INTERVAL = 300; // 5-minute totals
const HISTORY = 7; // days averaged for the forecast
const CLIP = 10_000; // W: a home's largest contribution to one total, the sensitivity of each total
const EPSILONS = [0.1, 1, 10]; // privacy budget per published total
const SEED = 'veil E6 seed 1';

const homes: MeterId[] = Array.from({ length: HOMES }, (_, i) => i + 1);
const load = simulateLoad(homes, DAYS, INTERVAL, SEED);
const perDay = 86_400 / INTERVAL;
const exact = Array.from({ length: load.samples }, (_, i) => homes.reduce((a, h) => a + Math.max(-CLIP, Math.min(CLIP, load.power.get(h)![i]!)), 0));

// Veil on the first day: run every round through the protocol and compare with the exact totals bit for bit.
const started = performance.now();
const { k, t } = choose(HOMES, DESIGN)!;
const group = setupGroup(homes, 1, k, t);
let equal = 0;
const veil: number[] = [];
for (let r = 0; r < perDay; r++) {
  const readings = new Map(homes.map((h) => [h, BigInt(Math.max(-CLIP, Math.min(CLIP, load.power.get(h)![r]!)))]));
  const result = runRound(group, r, readings, everyone(homes)).result;
  if (result.status !== 'published') throw new Error(`round ${r} ${result.status}`);
  veil.push(Number(result.total));
  if (result.total === BigInt(exact[r]!)) equal++;
}
console.log(`[e6] Veil totals equal to exact totals: ${equal}/${perDay}`);

const next = u32Stream(hkdf(Buffer.from(SEED), Buffer.from('e6')));
const laplace = (scale: number) => {
  const u = (next() + 0.5) / 2 ** 32 - 0.5;
  return -scale * Math.sign(u) * Math.log(1 - 2 * Math.abs(u));
};

const peaks = (series: readonly number[]) => Array.from({ length: DAYS }, (_, d) => Math.max(...series.slice(d * perDay, (d + 1) * perDay)));
const truePeaks = peaks(exact);
/** Mean absolute percentage error of "tomorrow's peak = mean of the last HISTORY days' peaks". */
function forecastError(series: readonly number[]): number {
  const p = peaks(series);
  let sum = 0;
  for (let d = HISTORY; d < DAYS; d++) {
    const forecast = p.slice(d - HISTORY, d).reduce((a, b) => a + b, 0) / HISTORY;
    sum += Math.abs(forecast - truePeaks[d]!) / truePeaks[d]!;
  }
  return sum / (DAYS - HISTORY);
}

const rows = [
  { source: 'exact totals', error: forecastError(exact) },
  { source: 'Veil totals', error: forecastError(exact), note: `equal to exact on ${equal}/${perDay} rounds run through the protocol` },
  ...EPSILONS.map((eps) => {
    const noisy = exact.map((x) => x + laplace(CLIP / eps));
    return { source: `Laplace noise, epsilon ${eps} per total`, error: forecastError(noisy), noise: CLIP / eps };
  }),
];
for (const r of rows) console.log(`[e6] ${r.source}: forecast error ${(r.error * 100).toFixed(2)}%`);

const seconds = ((performance.now() - started) / 1000).toFixed(1);
const md = [
  '# E6: does privacy cost forecasting accuracy?',
  '',
  `Generated by \`npm run e6\` on ${new Date().toISOString().slice(0, 10)}: ${environment()}. Seed "${SEED}". Run time ${seconds} s.`,
  '',
  `${HOMES} simulated homes (\`src/load.ts\`), ${DAYS} days of 5-minute totals, each reading clipped to ±${CLIP / 1000} kW. ` +
    `Forecast: tomorrow's peak total is the mean of the last ${HISTORY} daily peaks; error is the mean absolute ` +
    `percentage error over days ${HISTORY + 1}-${DAYS}. The differentially private version adds Laplace noise of scale ` +
    `${CLIP / 1000} kW / epsilon to every published total.`,
  '',
  `Veil check: all ${perDay} rounds of day 1 were run through the protocol (N = ${HOMES}, k = ${k}, t = ${t}); ` +
    `${equal}/${perDay} published totals equal the exact totals, so Veil's forecast is the exact one. This is an ` +
    'invariant of exact aggregation, not an experimental result.',
  '',
  '| totals | forecast error (MAPE) | noise scale per total |',
  '|---|---|---|',
  ...rows.map((r) => `| ${r.source} | ${(r.error * 100).toFixed(2)}% | ${'noise' in r ? `${(r.noise! / 1000).toFixed(1)} kW` : 'none'} |`),
];
writeResult('e6', md, { environment: environment(), seconds: Number(seconds), seed: SEED, equal, rounds: perDay, rows });
console.log(`[e6] done in ${seconds} s`);
